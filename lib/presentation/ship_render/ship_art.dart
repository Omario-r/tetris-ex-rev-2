import 'dart:ui' as ui;

import 'package:flutter/painting.dart';

/// Рисунок корабля: сцена в px рисунка (система `docs/design/ship-render.js`),
/// два слоя (D-011): корпус без предметов и предметы поверх.
///
/// Экраны и поле укладки обращаются к рисунку только через этот интерфейс —
/// следующий корабль подключается своей реализацией (сейчас — `RoninArt`).
abstract class ShipArt {
  /// W × H сцены, px рисунка.
  Size get sceneSize;

  /// Подложка под рисунком в клетке поля укладки там, где рисунка нет
  /// (клетки предмета вне его формы, клетки вне корпуса): фон рисунка в
  /// слоях не записан, а эталон сэмплирует полный рендер с космосом.
  Color get backdrop;

  /// Клетка рисунка → px сцены (как `px()`/`py()` эталона).
  Offset toScene(double x, double y);

  /// Слой 0: корпус без предметов. Записывается один раз и кешируется.
  ui.Picture get hullPicture;

  /// Слой 1: предметы (без плит корпуса), поверх контура корпуса.
  /// Записывается один раз и кешируется. Рисуется только под клипом формы
  /// предмета ([objectShape]) или поверх [hullPicture].
  ui.Picture get objectsPicture;

  /// Корпус для клетки поля во время сборки: без кромок деталей и контура
  /// корпуса, без щелей-огней (`render({edges: false, lights: false})`).
  /// Записывается лениво один раз и кешируется.
  ui.Picture get fieldBuildPicture;

  /// Корпус для собранной детали на поле: без кромок деталей и контура
  /// корпуса, со щелями-огнями (`render({edges: false})`). Записывается лениво
  /// один раз и кешируется.
  ui.Picture get fieldDonePicture;

  /// Контур борта «сюда дорастёт» (корпус + гондолы), px рисунка; штрих —
  /// токен `shipOutline`.
  Path get outline;

  /// Форма предмета слоя 1 по id детали (`'sensor'`, `'rcs_fl'`, `'rcs_fr'`,
  /// `'visor_l'`/`'visor_r'`, `'hatch_l'`/`'hatch_r'`), px рисунка; неизвестный
  /// id — [ArgumentError].
  Path objectShape(String partId);
}
