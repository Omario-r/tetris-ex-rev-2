/// Кусочек-полиомино для укладки.
///
/// `cells` — локальные координаты клеток кусочка (координата в системе
/// самого кусочка, не силуэта): нормализованные (`min x == 0`, `min y == 0`),
/// связные по 4-соседству, размер 3..5. Класс сам эти инварианты не
/// проверяет — их обеспечивает потребитель (генератор нарезки, T2).
class PackPiece {
  final int id;
  final List<({int x, int y})> cells;

  const PackPiece({required this.id, required this.cells});

  /// Число клеток кусочка.
  int get size => cells.length;
}
